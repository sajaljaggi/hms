-- Emergency department cases (ESI triage).
CREATE TABLE IF NOT EXISTS emergency_cases (
  id                 INT AUTO_INCREMENT PRIMARY KEY,
  patient_id         INT NULL,
  patient_name       VARCHAR(100) NOT NULL,
  age                INT NULL,
  gender             ENUM('male','female','other') NULL,
  contact_phone      VARCHAR(20) NULL,
  chief_complaint    VARCHAR(500) NOT NULL,
  arrival_mode       ENUM('walk_in','ambulance','referral') NOT NULL DEFAULT 'walk_in',
  triage_level       TINYINT NOT NULL,
  heart_rate         INT NULL,
  resp_rate          INT NULL,
  bp_systolic        INT NULL,
  bp_diastolic       INT NULL,
  spo2               INT NULL,
  temperature        DECIMAL(4,1) NULL,
  status             ENUM('waiting','in_treatment','admitted','discharged','transferred') NOT NULL DEFAULT 'waiting',
  assigned_doctor_id INT NULL,
  bed_allocation_id  INT NULL,
  created_by         INT NULL,
  arrived_at         DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  closed_at          DATETIME NULL,
  INDEX idx_er_queue (status, triage_level, arrived_at),
  INDEX idx_er_patient (patient_id),
  INDEX idx_er_doctor (assigned_doctor_id),
  INDEX idx_er_alloc (bed_allocation_id),
  INDEX idx_er_creator (created_by),
  FOREIGN KEY (patient_id) REFERENCES users(id) ON DELETE SET NULL,
  FOREIGN KEY (assigned_doctor_id) REFERENCES doctors(id) ON DELETE SET NULL,
  FOREIGN KEY (bed_allocation_id) REFERENCES bed_allocations(id) ON DELETE SET NULL,
  FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL
);
